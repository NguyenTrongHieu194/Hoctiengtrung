/**
 * Resolves complete Tonated Pinyin Information for Pinyin Mixer & Pronunciation Guide
 */
export function getMixerSyllableData(initial: string, final: string, tone: 1 | 2 | 3 | 4): TonatedPinyinDetail {
  const normFinal = final.replace("v", "ü");
  const pinyinMarked = applyPinyinTone(initial, normFinal, tone);

  // Check custom key
  const lookupKey = `${initial}_${normFinal}_${tone}`;
  if (MANDARIN_SYLLABLES_DATA[lookupKey]) {
    const item = MANDARIN_SYLLABLES_DATA[lookupKey];
    return {
      pinyin: item.pinyin || pinyinMarked,
      hanzi: item.hanzi,
      meaning: item.meaning,
      isValid: true
    };
  }

  // Check if valid combination exists in modern Mandarin
  const validFinalsForInitial = VALID_PINYIN_MATRIX[initial] || [];
  const isValid = validFinalsForInitial.includes(normFinal) || validFinalsForInitial.includes(final);

  if (!isValid) {
    return {
      pinyin: pinyinMarked,
      hanzi: "—",
      meaning: `Tổ hợp (${initial} + ${final}) không tồn tại trong tiếng Trung chuẩn. Hãy thử ghép ${initial} với các vần: ${validFinalsForInitial.slice(0, 6).join(", ")}...`,
      isValid: false,
      notes: "Tổ hợp không thông dụng"
    };
  }

  // Fallback for valid syllables not in explicit DB: generate accurate Pinyin & standard meaning
  return {
    pinyin: pinyinMarked,
    hanzi: "拼音",
    meaning: `Âm tiết chuẩn: ${pinyinMarked} (${initial} + ${final}) - Thanh ${tone}`,
    isValid: true
  };
}
