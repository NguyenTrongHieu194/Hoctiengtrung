// Tone placement rules on vowels
const TONE_VOWELS: Record<string, string[]> = {
  a: ["ā", "á", "ǎ", "à"],
  o: ["ō", "ó", "ǒ", "ò"],
  e: ["ē", "é", "ě", "è"],
  i: ["ī", "í", "ǐ", "ì"],
  u: ["ū", "ú", "ǔ", "ù"],
  ü: ["ǖ", "ǘ", "ǚ", "ǜ"],
  v: ["ǖ", "ǘ", "ǚ", "ǜ"]
};

/**
 * Standard Hanyu Pinyin tone mark placement algorithm
 */
export function applyPinyinTone(initial: string, rawFinal: string, tone: 1 | 2 | 3 | 4): string {
  let final = rawFinal;

  // Orthographic rules for ü:
  // After j, q, x, y, ü is written as u (e.g. ju, qu, xu, yu)
  const isJqxy = ["j", "q", "x", "y"].includes(initial.toLowerCase());
  if (isJqxy) {
    if (final === "ü" || final === "v") final = "u";
    if (final === "üe" || final === "ve") final = "ue";
    if (final === "üan" || final === "van") final = "uan";
    if (final === "ün" || final === "vn") final = "un";
  }

  // Zero initial rules for y and w
  let initStr = initial;
  if (!initStr) {
    if (final.startsWith("i")) {
      if (final === "i") { initStr = "y"; final = "i"; }
      else if (final === "in") { initStr = "y"; final = "in"; }
      else if (final === "ing") { initStr = "y"; final = "ing"; }
      else { initStr = "y"; final = final.slice(1); }
    } else if (final.startsWith("u") && final !== "ü") {
      if (final === "u") { initStr = "w"; final = "u"; }
      else { initStr = "w"; final = final.slice(1); }
    } else if (final.startsWith("ü") || final.startsWith("v")) {
      initStr = "y";
      final = final.replace(/^[üv]/, "u");
    }
  }

  const toneIdx = tone - 1;

  // Apply tone mark according to priority: a > o > e > (iu/ui -> second letter) > i > u > ü
  let tonatedFinal = final;
  if (final.includes("a")) {
    tonatedFinal = final.replace("a", TONE_VOWELS.a[toneIdx]);
  } else if (final.includes("o")) {
    tonatedFinal = final.replace("o", TONE_VOWELS.o[toneIdx]);
  } else if (final.includes("e")) {
    tonatedFinal = final.replace("e", TONE_VOWELS.e[toneIdx]);
  } else if (final.includes("iu")) {
    tonatedFinal = final.replace("u", TONE_VOWELS.u[toneIdx]);
  } else if (final.includes("ui")) {
    tonatedFinal = final.replace("i", TONE_VOWELS.i[toneIdx]);
  } else if (final.includes("i")) {
    tonatedFinal = final.replace("i", TONE_VOWELS.i[toneIdx]);
  } else if (final.includes("u")) {
    tonatedFinal = final.replace("u", TONE_VOWELS.u[toneIdx]);
  } else if (final.includes("ü")) {
    tonatedFinal = final.replace("ü", TONE_VOWELS.ü[toneIdx]);
  } else if (final.includes("v")) {
    tonatedFinal = final.replace("v", TONE_VOWELS.v[toneIdx]);
  }

  return `${initStr}${tonatedFinal}`;
}

